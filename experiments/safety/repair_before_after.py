"""Before and after the consolidated foundation safety repair, for every reproduced defect.

    python3 experiments/safety/repair_before_after.py            # exit 0 only if every line is as expected
    python3 experiments/safety/repair_before_after.py --write    # also rewrites experiments/safety/results/REPAIR_BEFORE_AFTER.md
    python3 experiments/safety/repair_before_after.py <commit>   # BEFORE from another commit (default 22bca1a, where the repair started)

BEFORE: the earlier commit, unpacked with `git archive` into a temp directory and run with its own code.
AFTER: this checkout. Both run experiments/safety/repair_scenarios.py from THIS checkout against their own code.
Needs git for BEFORE; without it only AFTER is checked.
"""
import io
import json
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
args = [a for a in sys.argv[1:] if not a.startswith("--")]
BASE = args[0] if args else "22bca1a"

CASES = [  # (key, field, what it shows, expected before, expected after)
    ("1a", "review_accepted", "1. Restriction requires A; rule establishes through A OR B; reviewer marks it enforced by A: accepted?", True, False),
    ("1a", "status_card_b_only", "1. ... the same record written into the rule; a person holding only B", "ESTABLISHED", "UNRESOLVED"),
    ("1b", "review_accepted", "1. Restriction says at least 1,000 nights; the rule checks at least 1; marked enforced: accepted?", True, False),
    ("1b", "status_5_nights", "1. ... the record written in; a person with 5 nights", "ESTABLISHED", "UNRESOLVED"),
    ("2", "status_no_record", "2. Rule needs \"not a member\"; nothing recorded about membership", "ESTABLISHED", "UNRESOLVED"),
    ("2", "status_member", "2. ... membership confirmed", "NOT_AVAILABLE", "NOT_AVAILABLE"),
    ("2", "status_recorded_absence", "2. ... the owner has recorded that they are not a member (new record type)", None, "ESTABLISHED"),
    ("3a", "A_or_B_holding_B", "3. Transfer allowed with card A OR card B; the person holds B", "NOT_CALCULATED", "CALCULATED"),
    ("3b", "figure_not_recorded", "3. Transfer needs a figure of at least 10; figure not recorded", "CALCULATED", "NOT_CALCULATED"),
    ("3c", "not_member_no_record", "3. Transfer needs \"not a member\"; nothing recorded", "CALCULATED", "NOT_CALCULATED"),
    ("3d", "blocked_rate_card_a", "3. Card A's earning rate is blocked (unchecked condition); card B's rule gives the same benefit", "CALCULATED", "NOT_CALCULATED"),
    ("3e", "blocked_credit_applies", "3. Card credit on a blocked rule; another card gives the same benefit: does the credit apply?", "ESTABLISHED", "UNRESOLVED"),
    ("4", "review_accepted", "4. \"Activate by December 31, 2026\" marked enforced by the rule's dates: accepted?", True, False),
    ("4", "status_in_window_not_activated", "4. ... inside the window, no activation recorded", "ESTABLISHED", "UNRESOLVED"),
    ("5", "march", "5. Card held January to May, ended May 31: the benefit in March", "NOT_AVAILABLE", "ESTABLISHED"),
    ("5", "june", "5. ... the benefit in June", "NOT_AVAILABLE", "NOT_AVAILABLE"),
    ("6a", "first_restriction_on_past_rule_without_declaration", "6. A first restriction added to a rule in force since 2025, nothing declared",
     "accepted", "refused: HISTORY_REWRITE"),
    ("6b", "status_after_removal_no_new_review", "6. The only reviewed restriction removed (declared); no new review yet", "ESTABLISHED", "UNRESOLVED"),
]


def run(tree):
    p = subprocess.run([sys.executable, os.path.join(HERE, "repair_scenarios.py"), tree], cwd=tree, capture_output=True, text=True,
                       env=dict(os.environ, PYTHONDONTWRITEBYTECODE="1"))
    if p.returncode != 0:
        sys.exit("the scenarios could not be run in %s:\n%s" % (tree, p.stderr[-2000:]))
    return json.loads(p.stdout.strip().splitlines()[-1])


old = None
blob = subprocess.run(["git", "archive", BASE], cwd=ROOT, capture_output=True) if shutil.which("git") else None
if blob is not None and blob.returncode == 0:
    old = tempfile.mkdtemp(prefix="prices-repair-before-")
    with tarfile.open(fileobj=io.BytesIO(blob.stdout)) as t:
        try:
            t.extractall(old, filter="data")
        except TypeError:
            t.extractall(old)
before = run(old) if old else None
after = run(ROOT)
lines, bad = [], []
lines += ["# Consolidated foundation safety repair: before and after, defect by defect", "",
          "Generated by `python3 experiments/safety/repair_before_after.py --write`. Do not edit by hand.",
          "BEFORE = commit `%s`, run with its own code. AFTER = this checkout. Scenarios: `experiments/safety/repair_scenarios.py` "
          "(invented data; each tree is given the classification form it accepts)." % BASE + ("" if old else " **BEFORE was not run: git or the commit is not available.**"),
          "", "| Defect and case | Before | After | |", "|---|---|---|---|"]
for key, field, what, want_b, want_a in CASES:
    a = after[key].get(field)
    b = before[key].get(field, None) if before else None
    ok = a == want_a and (before is None or want_b is None or b == want_b)
    if not ok:
        bad.append("%s %s" % (key, field))
    show = lambda v: "(no such record)" if v is None else ("yes" if v is True else "no" if v is False else v)   # noqa: E731
    lines.append("| %s | %s | %s | %s |" % (what, show(b) if before else "(not run)", show(a), "as expected" if ok else "**UNEXPECTED**"))
lines += ["", "Result: " + ("every line is as expected." if not bad else "UNEXPECTED: " + "; ".join(bad))]
print("\n".join(lines))
if "--write" in sys.argv and not bad:
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    with open(os.path.join(HERE, "results", "REPAIR_BEFORE_AFTER.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\nwritten to experiments/safety/results/REPAIR_BEFORE_AFTER.md")
if old:
    shutil.rmtree(old, ignore_errors=True)
sys.exit(1 if bad else 0)
