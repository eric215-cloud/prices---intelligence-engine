"""Before and after the foundation safety correction, on the same real sourced content.

    python3 experiments/safety/before_after.py              # prints the comparison; exit 0 only if every line is as expected
    python3 experiments/safety/before_after.py --write      # also rewrites experiments/safety/results/BEFORE_AFTER.md
    python3 experiments/safety/before_after.py <commit>     # compare with another commit (default c3b96a9, where the correction started)

BEFORE is the earlier commit, unpacked with `git archive` into a temp directory and run with its own code, sheets and
data. AFTER is this checkout. Nothing in the project is written: candidates are promoted only in throwaway copies,
and the proposal for the live rules is applied only in a copy. Needs git; without it only the AFTER column is shown.
"""
import io
import json
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
args = [a for a in sys.argv[1:] if not a.startswith("--")]
BASE = args[0] if args else "c3b96a9"
DATES = ("2026-11-12", "2026-11-17", "2027-03-15")
RANK = {"ESTABLISHED": 3, "CONDITIONAL": 2, "UNRESOLVED": 1, "NOT_AVAILABLE": 0}
lines, bad = [], []


def say(text=""):
    lines.append(text)
    print(text)


def expect(label, before, after, want_before, want_after):
    ok = after == want_after and (before is None or before == want_before)
    if not ok:
        bad.append(label)
    say("| %s | %s | %s | %s |" % (label, "(not run)" if before is None else before, after, "as expected" if ok else "UNEXPECTED (wanted %s -> %s)" % (want_before, want_after)))


def prices(tree, *a):
    env = {"PATH": os.environ.get("PATH", ""), "HOME": tempfile.gettempdir(), "PYTHONDONTWRITEBYTECODE": "1"}
    p = subprocess.run([sys.executable, "-m", "prices"] + list(a), cwd=tree, env=env, capture_output=True, text=True)
    return p.stdout


def statuses(tree, profile, day, root=None):
    """{entity: category} from the status report of one tree's code on one store."""
    rep = json.loads(prices(tree, *((["--root", root] if root else []) + ["--json", "status", "--profile", profile, "--as-of", day])))
    out = {}
    for key, label in (("derived_entitlements", "ESTABLISHED"), ("conditional", "CONDITIONAL"), ("unresolved", "UNRESOLVED")):
        for x in rep[key]:
            out[x["entity"]] = label
    return out, [(x["entity"], x["effective"]) for x in rep["personal_qualifications"]]


def scenario(tree):
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1")
    p = subprocess.run([sys.executable, os.path.join(HERE, "scenario.py"), tree], cwd=tree, env=env, capture_output=True, text=True)
    if p.returncode != 0:
        sys.exit("the experiment could not be run in %s:\n%s" % (tree, p.stderr[-1500:]))
    return json.loads(p.stdout.strip().splitlines()[-1])


def digest(tree, rel):
    import hashlib
    h = hashlib.sha256()
    for d, subdirs, names in os.walk(os.path.join(tree, rel)):
        subdirs[:] = sorted(s for s in subdirs if s != "__pycache__")
        for n in sorted(names):
            with open(os.path.join(d, n), "rb") as f:
                h.update(os.path.relpath(os.path.join(d, n), tree).encode() + f.read())
    return h.hexdigest()


old = None
blob = subprocess.run(["git", "archive", BASE], cwd=ROOT, capture_output=True) if shutil.which("git") else None
if blob is not None and blob.returncode == 0:
    old = tempfile.mkdtemp(prefix="prices-before-")
    with tarfile.open(fileobj=io.BytesIO(blob.stdout)) as t:
        try:
            t.extractall(old, filter="data")
        except TypeError:
            t.extractall(old)

say("# Foundation safety correction: before and after")
say()
say("Generated by `python3 experiments/safety/before_after.py --write`. Do not edit by hand.")
say("BEFORE = commit `%s` run with its own code. AFTER = this checkout. %s" % (BASE, "" if old else "**git or the commit was not available: BEFORE was not run.**"))
say("Every person is invented. Every rule is real sourced content; candidates are promoted only in throwaway copies.")

# ------------------------------------------------------------------------------------------- 1. the project store itself
say()
say("## 1. The project's own records are untouched; only how far the engine trusts them changed")
say()
if old:
    for rel in ("data", "profiles", "tables"):
        same = digest(old, rel) == digest(ROOT, rel)
        if not same:
            bad.append("files " + rel)
        say("- `%s/`: %s" % (rel, "identical to BEFORE, byte for byte" if same else "DIFFERENT from BEFORE"))
moved, total, wrong_way, personal_changed = [], 0, [], []
for prof in sorted(os.listdir(os.path.join(ROOT, "profiles"))):
    for day in DATES:
        new, new_personal = statuses(ROOT, prof, day)
        if not old:
            continue
        was, was_personal = statuses(old, prof, day)
        total += 1
        if was_personal != new_personal:
            personal_changed.append((prof, day))
        for e in sorted(set(was) | set(new)):
            a, b = was.get(e, "NOT_AVAILABLE"), new.get(e, "NOT_AVAILABLE")
            if a != b:
                moved.append((prof, day, e, a, b))
                if RANK[b] > RANK[a] or b == "NOT_AVAILABLE":
                    wrong_way.append((prof, day, e, a, b))
if old:
    if wrong_way or personal_changed:
        bad.append("direction of change")
    say("- %d status reports compared (every profile, %d dates). Personal qualifications: %s."
        % (total, len(DATES), "identical in all" if not personal_changed else "CHANGED in %s" % personal_changed))
    say("- %d derived answers changed, every one of them from ESTABLISHED or CONDITIONAL down to UNRESOLVED; none moved up and none disappeared%s."
        % (len(moved), "" if not wrong_way else " EXCEPT %s" % wrong_way))
    say()
    say("| Profile | As of | Entity | Before | After |")
    say("|---|---|---|---|---|")
    for prof, day, e, a, b in moved:
        if day == DATES[1]:
            say("| %s | %s | %s | %s | %s |" % (prof, day, e, a, b))
    say()
    say("(Shown for %s; the other dates differ the same way. The reason in every case: the rule's restrictions and open questions have no "
        "class from a reviewer yet, so the rule is not relied on.)" % DATES[1])

# --------------------------------------------------------------------------------- 2. the live rules, with the proposal
say()
say("## 2. The verified rules in the store: before, after, and after a reviewer applies the proposed classes (in a copy)")
say()
sys.path.insert(0, HERE)
